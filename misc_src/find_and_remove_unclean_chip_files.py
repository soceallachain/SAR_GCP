import os
import re

def get_matching_files(list_file, chip_dir):
    matching_files = []
    
    # Read the list of clean chips
    with open(list_file, 'r') as f:
        clean_chips = f.readlines()
    
    # Process each line in the file
    for chip in clean_chips:
        chip = chip.strip()  # Remove any whitespace
        
        # Extract CRC, burst number, and chip number
        match = re.match(r'(\w+)_burst#(\d+)_chip#(\d+)', chip)
        if match:
            crc, burst_num, chip_num = match.groups()
            
            # Search for matching file in chip_dir
            for filename in os.listdir(chip_dir):
                if crc in filename and f"burst#{burst_num}" in filename and f"chip#{chip_num}" in filename:
                    matching_files.append(os.path.join(chip_dir, filename))
                    break  # Stop searching after finding a match
    
    return matching_files

