def find_matching_files(file_path: str, chip_dir: str):
    matching_files = []
    
    # Ensure the directory exists
    if not os.path.isdir(chip_dir):
        raise FileNotFoundError(f"Directory '{chip_dir}' not found.")
    
    # Open and read the file
    with open(file_path, 'r') as f:
        for line in f:
            line = line.strip()
            match = re.match(r"(.+)_burst#(\d+)_chip#(\d+)", line)
            
            if match:
                crc, burst_number, chip_number = match.groups()
                
                # Search for the matching file in the directory
                for filename in os.listdir(chip_dir):
                    if crc in filename and f"burst#{burst_number}" in filename and f"chip#{chip_number}" in filename:
                        matching_files.append(os.path.join(chip_dir, filename))
                        #break  # Stop searching once the file is found
            else:
                print(f"Warning: Line format incorrect - {line}")
    
    return matching_files


import shutil

def copy_excluding_list(src: str, dest: str, exclude_files: list):
    if not os.path.exists(src):
        raise FileNotFoundError(f"Source directory '{src}' not found.")
    
    if not os.path.exists(dest):
        os.makedirs(dest)  # Create destination directory if it doesn't exist
    
    # Convert exclude_files to a set for fast lookup
    exclude_files = set(exclude_files)
    
    # Copy files excluding the ones in the list
    for item in os.listdir(src):
        s = os.path.join(src, item)
        d = os.path.join(dest, item)
        
        if os.path.isfile(s) and s not in exclude_files:
            shutil.copy2(s, d)



